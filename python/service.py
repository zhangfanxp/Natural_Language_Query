def migrate_legacy_sample_database_copy() -> bool:
    if not SAMPLE_DATABASE_SOURCE.is_file() or not SAMPLE_DATABASE_COPY.is_file():
        return False

    digest = hashlib.sha256(SAMPLE_DATABASE_COPY.read_bytes()).hexdigest()
    if digest != LEGACY_SAMPLE_DATABASE_SHA256:
        return False

    SAMPLE_DATABASE_COPY.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    temporary_path = SAMPLE_DATABASE_COPY.with_name(
        f".{SAMPLE_DATABASE_COPY.name}.{os.getpid()}.tmp"
    )
    try:
        shutil.copy2(SAMPLE_DATABASE_SOURCE, temporary_path)
        os.chmod(temporary_path, 0o600)
        os.replace(temporary_path, SAMPLE_DATABASE_COPY)
    finally:
        temporary_path.unlink(missing_ok=True)
    return True


